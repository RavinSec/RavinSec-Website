type Part = string | { text: string; bold?: boolean };

type Block =
  | { kind: "h2" | "h3"; text: string }
  | { kind: "p"; parts: Part[] }
  | { kind: "ul" | "ol"; items: Part[][] };

type SeedPost = {
  title: string;
  slug: string;
  publishedAt: string;
  excerpt: string;
  category: "threat-analysis" | "guide" | "announcement" | "remediation" | "update";
  blocks: Block[];
};

function textNode(part: Part) {
  const value = typeof part === "string" ? part : part.text;
  const bold = typeof part === "string" ? false : Boolean(part.bold);
  return {
    type: "text",
    version: 1,
    text: value,
    detail: 0,
    format: bold ? 1 : 0,
    mode: "normal",
    style: "",
  };
}

function blockNode(block: Block, listValue = 1) {
  if (block.kind === "h2" || block.kind === "h3") {
    return {
      type: "heading",
      tag: block.kind,
      version: 1,
      direction: "rtl" as const,
      format: "",
      indent: 0,
      children: [textNode(block.text)],
    };
  }

  if (block.kind === "p") {
    return {
      type: "paragraph",
      version: 1,
      direction: "rtl" as const,
      format: "",
      indent: 0,
      textFormat: 0,
      textStyle: "",
      children: block.parts.map(textNode),
    };
  }

  const ordered = block.kind === "ol";
  return {
    type: "list",
    listType: ordered ? "number" : "bullet",
    tag: ordered ? "ol" : "ul",
    start: 1,
    version: 1,
    direction: "rtl" as const,
    format: "",
    indent: 0,
    children: block.items.map((parts, index) => ({
      type: "listitem",
      version: 1,
      value: listValue + index,
      direction: "rtl" as const,
      format: "",
      indent: 0,
      children: parts.map(textNode),
    })),
  };
}

function body(blocks: Block[]) {
  return {
    root: {
      type: "root",
      version: 1,
      direction: "rtl" as const,
      format: "" as const,
      indent: 0,
      children: blocks.map((block) => blockNode(block)),
    },
  };
}

